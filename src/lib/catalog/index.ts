import { asc } from "drizzle-orm";
import type { DB } from "../db";
import { subtopics, topics } from "../db/schema";
import type { Skill, Specialization } from "../skills";

export type CatalogEntry = {
  id: string;
  topicId: string;
  topicTitle: string;
  title: string;
  summary: string;
  skill: Skill;
  difficulty: number;
  prerequisites: string[];
  tracks: string[];
};

let cache: { at: number; entries: CatalogEntry[] } | null = null;

/** Loads the seeded catalog from the database (memoised for 5 minutes per server instance). */
export async function loadCatalog(db: DB): Promise<CatalogEntry[]> {
  if (cache && Date.now() - cache.at < 5 * 60_000) return cache.entries;
  const [topicRows, rows] = await Promise.all([
    db.select().from(topics),
    db.select().from(subtopics).orderBy(asc(subtopics.sortOrder)),
  ]);
  const topicTitle = new Map(topicRows.map((t) => [t.id, t.title]));
  const entries = rows.map((r) => ({
    id: r.id,
    topicId: r.topicId,
    topicTitle: topicTitle.get(r.topicId) ?? r.topicId,
    title: r.title,
    summary: r.summary,
    skill: r.skill as Skill,
    difficulty: r.difficulty,
    prerequisites: r.prerequisites,
    tracks: r.tracks,
  }));
  cache = { at: Date.now(), entries };
  return entries;
}

export function catalogById(entries: CatalogEntry[]): Map<string, CatalogEntry> {
  return new Map(entries.map((e) => [e.id, e]));
}

export function eligibleFor(entries: CatalogEntry[], spec: Specialization): CatalogEntry[] {
  return entries.filter((e) => e.tracks.includes("core") || e.tracks.includes(spec));
}

/** Week-1 candidates: easiest subtopics with no prerequisites. Their decks are pre-generated by the seed script. */
export function isStarter(e: CatalogEntry): boolean {
  return e.difficulty === 1 && e.prerequisites.length === 0;
}
